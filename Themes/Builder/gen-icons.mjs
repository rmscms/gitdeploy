// Generates Themes/Icons.xaml (WPF StreamGeometry resources "Icon.<name>") from Themes/Builder/icons.json.
// Run:  node Themes/Builder/gen-icons.mjs
// Icons are 24x24 stroke icons; AppIcon.Kind="<name>" draws them with the current Foreground (see Behaviors/AppIcon.cs).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const { icons } = JSON.parse(fs.readFileSync(path.join(here, 'icons.json'), 'utf8'));
const f = (n) => String(+n.toFixed(3));

// ---- SVG path -> explicit WPF path mini-language (flags separated, numbers explicit) ----
function normalizePath(d) {
  const out = [];
  let i = 0;
  const num = () => {
    const m = /^[\s,]*(-?(?:\d*\.\d+|\d+\.?)(?:[eE][-+]?\d+)?)/.exec(d.slice(i));
    if (!m) throw new Error('bad number at ' + i + ' in ' + d);
    i += m[0].length;
    return +m[1];
  };
  const flag = () => {
    while (d[i] === ' ' || d[i] === ',') i++;
    const c = d[i++];
    if (c !== '0' && c !== '1') throw new Error('bad arc flag in ' + d);
    return c;
  };
  const argc = { M: 2, L: 2, H: 1, V: 1, C: 6, S: 4, Q: 4, T: 2, A: 7, Z: 0 };
  let cmd = '';
  while (i < d.length) {
    while (d[i] === ' ' || d[i] === ',') i++;
    if (i >= d.length) break;
    if (/[A-Za-z]/.test(d[i])) { cmd = d[i++]; if (cmd === 'Z' || cmd === 'z') { out.push('Z'); continue; } }
    else if (cmd === 'M') cmd = 'L'; else if (cmd === 'm') cmd = 'l';
    const n = argc[cmd.toUpperCase()];
    const vals = [];
    if (cmd.toUpperCase() === 'A') {
      vals.push(f(num()), f(num()), f(num()), flag(), flag(), f(num()), f(num()));
    } else {
      for (let k = 0; k < n; k++) vals.push(f(num()));
    }
    out.push(cmd + vals.join(' '));
  }
  return out.join(' ');
}
const rect = (x, y, w, h, r = 0) => r
  ? `M${f(x + r)} ${f(y)} H${f(x + w - r)} A${f(r)} ${f(r)} 0 0 1 ${f(x + w)} ${f(y + r)} V${f(y + h - r)} A${f(r)} ${f(r)} 0 0 1 ${f(x + w - r)} ${f(y + h)} H${f(x + r)} A${f(r)} ${f(r)} 0 0 1 ${f(x)} ${f(y + h - r)} V${f(y + r)} A${f(r)} ${f(r)} 0 0 1 ${f(x + r)} ${f(y)} Z`
  : `M${f(x)} ${f(y)} H${f(x + w)} V${f(y + h)} H${f(x)} Z`;
const ellipse = (cx, cy, rx, ry) => `M${f(cx - rx)} ${f(cy)} A${f(rx)} ${f(ry)} 0 1 0 ${f(cx + rx)} ${f(cy)} A${f(rx)} ${f(ry)} 0 1 0 ${f(cx - rx)} ${f(cy)} Z`;
const attr = (s, k, def = 0) => { const m = new RegExp('\\b' + k + '="([^"]*)"').exec(s); return m ? +m[1] : def; };

function toGeometry(svg) {
  const parts = [];
  for (const m of svg.matchAll(/<(path|rect|circle|ellipse)\b([^>]*)\/?>/g)) {
    const [, tag, a] = m;
    if (tag === 'path') parts.push(normalizePath(/\bd="([^"]*)"/.exec(a)[1]));
    else if (tag === 'rect') parts.push(rect(attr(a, 'x'), attr(a, 'y'), attr(a, 'width'), attr(a, 'height'), attr(a, 'rx')));
    else if (tag === 'circle') parts.push(ellipse(attr(a, 'cx'), attr(a, 'cy'), attr(a, 'r'), attr(a, 'r')));
    else parts.push(ellipse(attr(a, 'cx'), attr(a, 'cy'), attr(a, 'rx'), attr(a, 'ry')));
  }
  return parts.join(' ');
}

const names = Object.keys(icons).sort();
const body = names.map((n) => `    <StreamGeometry x:Key="Icon.${n}">${toGeometry(icons[n])}</StreamGeometry>`).join('\r\n');
const xaml = `<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"\r\n                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">\r\n    <!-- GENERATED by Themes/Builder/gen-icons.mjs from icons.json — do not edit by hand. 24x24 stroke icons. -->\r\n${body}\r\n</ResourceDictionary>\r\n`;
fs.writeFileSync(path.join(here, '..', 'Icons.xaml'), xaml);
console.log(`Icons.xaml written: ${names.length} icons`);
